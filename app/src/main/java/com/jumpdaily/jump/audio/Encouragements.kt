package com.jumpdaily.jump.audio

/**
 * 儿童鼓励语语料池（按场景分组）。集中维护在此，有两个目的：
 * 1. [com.jumpdaily.jump.ui.viewmodel.TrainingViewModel] 训练时按场景随机轮换、避免连续重复；
 * 2. [tools/gen_voice_pack.py] 离线把每条语料合成为音频，生成「语音包」，
 *    打包进 assets/voice 后，任意手机播出来的音色都完全一致、不依赖厂商 TTS 引擎。
 *
 * 模板里的 {n} 在运行时替换为真实计数；带 {n} 的句子是动态的，生成脚本会把它拆成
 * 「前缀/后缀」两段各产出音频，运行时 VoiceSpeaker 用「前缀 + 中文数字(num_<字>.wav) + 后缀」
 * 拼接播放，整句仍是同一套童音（见 VoiceSpeaker.speak(template, number)）。
 *
 * 语料编排原则（儿童向）：
 * - **够多**：每个池 6 句以上，轮换取模也不容易撞车，孩子不会听腻；
 * - **够短**：一句话 8~16 字，TTS 一两秒念完，不打断跳绳节奏；
 * - **够具体**：夸「节奏稳/连跳不断/姿势标准」，而不是空泛的「真棒」；
 * - **有画面**：气球、火箭、小超人这类孩子熟悉的东西，比抽象表扬更有效。
 */
object Encouragements {
    /** 跳得慢 / 休息时（频率最高）的加油语——池子最大，避免老重复同一句。 */
    val cheerSlowPool = listOf(
        "加油，你可以的！",
        "再坚持一下，你超棒的！",
        "慢慢来，跳跳星陪着你呢～",
        "别急，一个一个稳稳跳！",
        "你跳得真认真，继续哦！",
        "深呼吸，我们再来几个！",
        "小手甩起来，脚步轻轻跟上～",
        "真厉害，已经跳了这么多啦！",
        "像小兔子一样，轻轻跳起来！",
        "脚尖点地，和小弹簧一样弹！",
        "数着拍子跳，一二、一二！",
        "加油加油，你离目标更近啦！",
        "手腕转一转，绳子就听话啦！",
        "抬头挺胸，你是最神气的小选手！",
        "累了就歇一歇，跳跳星等你～",
        "再来五个，我们试试看！"
    )

    /** 每跳满 5 个的报数/里程碑庆祝语（{n} = 当前个数）。 */
    val milestonePool = listOf(
        "太棒啦，已经跳了 {n} 个！",
        "哇，{n} 个啦，你真是跳绳小明星！",
        "{n} 个！跳跳星给你点赞👍",
        "好厉害，已经 {n} 个咯！",
        "{n} 个到手，继续冲鸭！",
        "哇塞，{n} 个啦，像小火箭一样快！",
        "已经 {n} 个，你今天状态超好！",
        "{n} 个！这是要破纪录的节奏呀！"
    )

    /** 节奏又快又稳时的夸奖语（静态，可打包）。 */
    val steadyPool = listOf(
        "节奏很稳，加油！",
        "哇，跳得又稳又快！",
        "保持这个节奏，太帅了！",
        "节奏感超棒，继续冲！",
        "哒哒哒，像小马跑起来！",
        "这个速度，教练都要夸你！",
        "稳得像小闹钟，太准啦！",
        "又快又稳，你是跳绳小旋风！"
    )

    /** 动作不规范时的纠正提示（静态，可打包）。 */
    val correctionPool = listOf(
        "站稳小手，把绳子甩起来",
        "双脚并拢轻轻跳哦",
        "绳子甩圆一点，身体别晃～",
        "跳低一点，轻轻落地更省力",
        "手腕用力，胳膊不用抬太高",
        "眼睛看前方，身体就不晃啦"
    )

    /** 达成每日目标时的专属庆祝语（{n} 为占位，运行时动态）。 */
    val goalPool = listOf(
        "达成今日目标啦，你超厉害！",
        "今日目标完成！你就是跳绳小超人！",
        "太厉害了，今天的目标达成咯！",
        "目标达成！给自己鼓个掌吧！",
        "哇，今日目标被你拿下啦，好样的！"
    )

    /** 训练完成时的总结语（{n} = 总个数，运行时动态）。 */
    val completePool = listOf(
        "完成！今天跳了 {n} 个，真是跳绳小超人！",
        "今天的跳绳结束啦，一共 {n} 个，超棒！",
        "{n} 个达成，你太了不起了！",
        "收工！{n} 个好成绩，明天继续！",
        "{n} 个，跳跳星为你骄傲！"
    )

    /** 连击（连续不间断）到整数关口的喝彩语（{n} = 连击个数）。 */
    val comboPool = listOf(
        "连续 {n} 个没断，太牛啦！",
        "哇，连跳 {n} 个，像装了小马达！",
        "{n} 连击！跳绳小旋风就是你！",
        "一口气 {n} 个，厉害得飞起来！"
    )

    /** 训练途中弹出「小奖品 / 积分奖励」时的喝彩语（静态，可打包）。 */
    val prizePool = listOf(
        "哇，你得到了一个小奖励！",
        "跳得太好啦，奖励你一个小惊喜！",
        "表现超棒，这是给你的小礼物！",
        "收下这颗小星星，你值得！",
        "奖励来啦，继续保持哦！",
        "太厉害了，又拿到一个奖励！"
    )

    /** 开始训练时的开场鼓励（静态，可打包）。 */
    val startPool = listOf(
        "准备好啦，我们开始跳吧！",
        "来，和跳跳星一起数起来！",
        "预备，开始！加油小选手！",
        "今天也要跳得开心哦！"
    )

    /** 全部语料（生成脚本用：会过滤掉含 {n} 的动态句子再合成）。 */
    val allPools: Map<String, List<String>> = mapOf(
        "cheerSlow" to cheerSlowPool,
        "milestone" to milestonePool,
        "steady" to steadyPool,
        "correction" to correctionPool,
        "goal" to goalPool,
        "complete" to completePool,
        "combo" to comboPool,
        "prize" to prizePool,
        "start" to startPool
    )
}
